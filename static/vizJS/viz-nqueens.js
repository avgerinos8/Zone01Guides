/* ══════════════════════════════════════════════════════════════════════════
   viz-nqueens.js — step visualizer for 4x4 N-Queens backtracking
   (piscine-go-week2, N βασίλισσες section).

   Root id: #nqueens-viz. Built on VizWaitFor from viz-common.js. Neither
   viz-common.js nor viz-style.css is modified — this uses .vz-grid /
   .vz-grid-cell (the 2D layer that shipped ahead of any real user) plus the
   deck's own .reset-quiz-btn / .quiz-code-block / .glossary-strip.

   Step sequence generated by actually running the backtracking algorithm
   in Python first (place / reject / remove / deadend / solution), then
   transcribed here 1:1 — not re-derived by hand, so it cannot silently
   diverge from what SolveQueens really does on a 4x4 board.

   Step granularity: every column tried in every row is its own step,
   including rejected ones — nothing is folded into the row that contains it.
   ══════════════════════════════════════════════════════════════════════════ */
(function () {
  var N = 4;

  // One entry per event from the real backtracking run on N=4.
  // kind: place | reject | remove | deadend | solution
  var RAW = [
    ["place", 0, 0, [0, -1, -1, -1]],
    ["reject", 1, 0],
    ["reject", 1, 1],
    ["place", 1, 2, [0, 2, -1, -1]],
    ["reject", 2, 0],
    ["reject", 2, 1],
    ["reject", 2, 2],
    ["reject", 2, 3],
    ["deadend", 2],
    ["remove", 1, 2],
    ["place", 1, 3, [0, 3, -1, -1]],
    ["reject", 2, 0],
    ["place", 2, 1, [0, 3, 1, -1]],
    ["reject", 3, 0],
    ["reject", 3, 1],
    ["reject", 3, 2],
    ["reject", 3, 3],
    ["deadend", 3],
    ["remove", 2, 1],
    ["reject", 2, 2],
    ["reject", 2, 3],
    ["deadend", 2],
    ["remove", 1, 3],
    ["deadend", 1],
    ["remove", 0, 0],
    ["place", 0, 1, [1, -1, -1, -1]],
    ["reject", 1, 0],
    ["reject", 1, 1],
    ["reject", 1, 2],
    ["place", 1, 3, [1, 3, -1, -1]],
    ["place", 2, 0, [1, 3, 0, -1]],
    ["reject", 3, 0],
    ["reject", 3, 1],
    ["place", 3, 2, [1, 3, 0, 2]],
    ["solution", [1, 3, 0, 2]]
  ];

  var NOTES = {
    place: function (row, col) {
      return "Θέτω βασίλισσα στη γραμμή " + row + ", στήλη " + col + " — CHOOSE.";
    },
    reject: function (row, col) {
      return "isSafe(board, " + row + ", " + col + ") → false. Απειλείται, δεν κατεβαίνουμε καν εδώ — PRUNE.";
    },
    remove: function (row, col) {
      return "Καμία επιλογή στην επόμενη γραμμή δεν δούλεψε. Ακυρώνω τη βασίλισσα (" + row + ", " + col + ") — UN-CHOOSE.";
    },
    deadend: function (row) {
      return "Καμία στήλη της γραμμής " + row + " δεν οδηγεί πουθενά. Επιστρέφω nil στον καλούντα.";
    },
    solution: function (b) {
      return "row == len(board): κάθε γραμμή έχει βασίλισσα. Λύση: [" + b.join(" ") + "].";
    }
  };

  function buildSteps() {
    var steps = [];
    var board = [-1, -1, -1, -1];
    steps.push({ board: board.slice(), row: 0, col: -1, kind: "start", note: "SolveQueens(board, 0) — καμία γραμμή δεν έχει ακόμη βασίλισσα." });
    RAW.forEach(function (ev) {
      var kind = ev[0];
      if (kind === "place") {
        board = ev[3].slice();
        steps.push({ board: board.slice(), row: ev[1], col: ev[2], kind: "place", note: NOTES.place(ev[1], ev[2]) });
      } else if (kind === "reject") {
        steps.push({ board: board.slice(), row: ev[1], col: ev[2], kind: "reject", note: NOTES.reject(ev[1], ev[2]) });
      } else if (kind === "remove") {
        steps.push({ board: board.slice(), row: ev[1], col: ev[2], kind: "remove-before", note: NOTES.remove(ev[1], ev[2]) });
        board = board.slice();
        board[ev[1]] = -1;
        steps.push({ board: board.slice(), row: ev[1], col: -1, kind: "remove-after", note: "Το board τώρα είναι [" + board.join(" ") + "]." });
      } else if (kind === "deadend") {
        steps.push({ board: board.slice(), row: ev[1], col: -1, kind: "deadend", note: NOTES.deadend(ev[1]) });
      } else if (kind === "solution") {
        steps.push({ board: ev[1].slice(), row: N, col: -1, kind: "solution", note: NOTES.solution(ev[1]) });
      }
    });
    return steps;
  }

  VizWaitFor("nqueens-viz", function (root) {
    var steps = buildSteps();
    var cur = 0, timer = null, speed = 1;

    root.innerHTML =
      '<div class="vz-controls">' +
      '  <button class="reset-quiz-btn" data-act="prev">← prev step</button>' +
      '  <button class="reset-quiz-btn" data-act="next">next step →</button>' +
      '  <button class="reset-quiz-btn" data-act="reset">⟲ reset</button>' +
      '  <button class="reset-quiz-btn vz-btn-stable" data-act="play">▶ autoplay ↕</button>' +
      '</div>' +
      '<div class="quiz-code-block">' +
      '  <div class="vz-grid" style="--vz-grid-cols:4" data-el="grid"></div>' +
      '</div>' +
      '<div class="glossary-group"><div class="glossary-strip">' +
      '  <div class="gs-pill"><span class="gs-name">board</span><span class="gs-def" data-el="board">—</span></div>' +
      '  <div class="gs-pill"><span class="gs-name">ενέργεια</span><span class="gs-def" data-el="kind">—</span></div>' +
      '</div></div>' +
      '<p data-el="note" style="margin-top:6px"></p>' +
      '<p data-el="count" style="opacity:.55"></p>';

    var grid = root.querySelector('[data-el="grid"]');
    var cells = [];
    for (var k = 0; k < N * N; k++) {
      var c = document.createElement("div");
      c.className = "vz-grid-cell";
      grid.appendChild(c); cells.push(c);
    }

    var KIND_LABEL = {
      start: "—", place: "choose", reject: "prune",
      "remove-before": "un-choose", "remove-after": "un-choose",
      deadend: "αδιέξοδο", solution: "λύση"
    };

    function render() {
      var s = steps[cur];
      for (var k = 0; k < cells.length; k++) {
        cells[k].textContent = "";
        cells[k].className = "vz-grid-cell";
      }
      for (var r = 0; r < N; r++) {
        var col = s.board[r];
        if (col >= 0) {
          var idx = r * N + col;
          cells[idx].textContent = "Q";
          cells[idx].classList.add(s.kind === "solution" ? "vz-highlight-b" : "vz-highlight-a");
        }
      }
      if ((s.kind === "place" || s.kind === "reject") && s.row < N && s.col >= 0) {
        var cu = s.row * N + s.col;
        cells[cu].textContent = (s.kind === "reject") ? "✕" : "Q";
        cells[cu].classList.remove("vz-highlight-a");
        cells[cu].classList.add(s.kind === "reject" ? "vz-highlight-c" : "vz-highlight-b");
      }
      root.querySelector('[data-el="board"]').textContent = "[" + s.board.join(" ") + "]";
      root.querySelector('[data-el="kind"]').textContent = KIND_LABEL[s.kind];
      root.querySelector('[data-el="note"]').textContent = s.note;
      root.querySelector('[data-el="count"]').textContent = "βήμα " + (cur + 1) + " από " + steps.length;
      root.querySelector('[data-act="prev"]').disabled = (cur === 0);
      root.querySelector('[data-act="next"]').disabled = (cur === steps.length - 1);
    }

    function stopPlay() {
      if (timer) { clearInterval(timer); timer = null; }
      root.querySelector('[data-act="play"]').textContent = "▶ autoplay ↕";
    }
    function startPlay() {
      root.querySelector('[data-act="play"]').textContent = "⏸ " + speed.toFixed(1) + "x ↕";
      timer = setInterval(function () {
        if (cur < steps.length - 1) { cur++; render(); } else { stopPlay(); }
      }, 900 / speed);
    }
    root.addEventListener("click", function (e) {
      var act = e.target.getAttribute && e.target.getAttribute("data-act");
      if (!act) return;
      if (act === "prev" && cur > 0) { stopPlay(); cur--; render(); }
      if (act === "next" && cur < steps.length - 1) { stopPlay(); cur++; render(); }
      if (act === "reset") { stopPlay(); cur = 0; render(); }
      if (act === "play") { if (timer) { stopPlay(); } else { startPlay(); } }
    });
    root.querySelector('[data-act="play"]').addEventListener("wheel", function (e) {
      e.preventDefault();
      speed = Math.min(4, Math.max(0.5, speed + (e.deltaY < 0 ? 0.5 : -0.5)));
      if (timer) { stopPlay(); startPlay(); }
      else { this.textContent = "▶ " + speed.toFixed(1) + "x ↕"; }
    }, { passive: false });

    render();
  });
})();
